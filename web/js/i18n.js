let LANG = 'ro';
function setLang(l) { LANG = TEXTS[l] ? l : 'ro'; document.documentElement.lang = LANG; }
function t(key, params) {
  let s = (TEXTS[LANG] && TEXTS[LANG][key]);
  if (s === undefined) s = TEXTS.ro[key];
  if (s === undefined) return key;
  if (typeof s !== 'string') return s;
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined && params[k] !== null ? params[k] : m));
  return s;
}
function errText(code) {
  if (!code) return t('err_generic', { x: '?' });
  const [k, x] = String(code).split(/:(.*)/s);
  const key = 'err_' + k;
  if (TEXTS.ro[key]) return t(key, { x: x || '' });
  return t('err_generic', { x: code });
}
